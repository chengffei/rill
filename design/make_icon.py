"""Generates design/appIcon.svg: a power grid that runs like a creek.

Three circuit traces follow one meandering course, two tributary traces join
it at grid nodes, and bright pulses sit along the flow."""
import math

def bez(p0, p1, p2, p3, t):
    u = 1 - t
    return tuple(u**3*a + 3*u*u*t*b + 3*u*t*t*c + t**3*d for a, b, c, d in zip(p0, p1, p2, p3))

# Main course as two cubic segments, left-top to right-bottom.
SEGS = [((60, 330), (330, 250), (330, 560), (520, 540)),
        ((520, 540), (710, 520), (700, 790), (980, 740))]

def course(n=160):
    pts = []
    for seg in SEGS:
        for i in range(n):
            pts.append(bez(*seg, i / n))
    pts.append(SEGS[-1][3])
    return pts

def offset(pts, d):
    out = []
    for i, (x, y) in enumerate(pts):
        a = pts[max(0, i - 1)]; b = pts[min(len(pts) - 1, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        L = math.hypot(dx, dy) or 1
        out.append((x - dy / L * d, y + dx / L * d))
    return out

def path(pts):
    return "M " + " L ".join(f"{x:.1f} {y:.1f}" for x, y in pts)

base = course()
lanes = [offset(base, d) for d in (-56, 0, 56)]

svg = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><!-- Rill app icon: a power grid that flows like a creek. Generated by make_icon.py. -->',
'<defs>',
'<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#12304A"/><stop offset="1" stop-color="#0A1724"/></linearGradient>',
'<linearGradient id="flow" gradientUnits="userSpaceOnUse" x1="100" y1="300" x2="924" y2="760"><stop offset="0" stop-color="#4FB3FF"/><stop offset="1" stop-color="#3EE0A6"/></linearGradient>',
'<filter id="glow" filterUnits="userSpaceOnUse" x="0" y="0" width="1024" height="1024"><feGaussianBlur stdDeviation="10"/></filter>',
'<clipPath id="sq"><rect x="100" y="100" width="824" height="824" rx="184" ry="184"/></clipPath>',
'</defs>',
'<rect x="100" y="100" width="824" height="824" rx="184" ry="184" fill="url(#bg)"/>',
'<g clip-path="url(#sq)">',
# creek bed
f'<path d="{path(base)}" fill="none" stroke="#163C55" stroke-width="210" stroke-linecap="round" stroke-linejoin="round"/>',
]

# Tributaries: grid-style traces (straight, one 45-degree bend) ending in a node.
def tributary(lane, idx, dx, dy, bend):
    jx, jy = lane[idx]
    mx, my = jx + bend[0], jy + bend[1]
    ex, ey = mx + dx, my + dy
    return (jx, jy), (mx, my), (ex, ey)

tribs = [tributary(lanes[0], 175, 0, -150, (-70, -70)),
         tributary(lanes[2], 120, 0, 150, (70, 70))]

glow = []
for (j, m, e) in tribs:
    glow.append(f'M {j[0]:.1f} {j[1]:.1f} L {m[0]:.1f} {m[1]:.1f} L {e[0]:.1f} {e[1]:.1f}')
lane_d = [path(l) for l in lanes]

# soft glow under all traces
svg.append('<g filter="url(#glow)" opacity=".75" fill="none" stroke="url(#flow)" stroke-width="18" stroke-linecap="round" stroke-linejoin="round">')
svg += [f'<path d="{d}"/>' for d in lane_d + glow]
svg.append('</g>')
# crisp traces
svg.append('<g fill="none" stroke="url(#flow)" stroke-width="13" stroke-linecap="round" stroke-linejoin="round">')
svg += [f'<path d="{d}"/>' for d in lane_d + glow]
svg.append('</g>')
# nodes at tributary heads and joins
for (j, m, e) in tribs:
    svg.append(f'<circle cx="{e[0]:.1f}" cy="{e[1]:.1f}" r="26" fill="#0E2335" stroke="url(#flow)" stroke-width="13"/>')
    svg.append(f'<circle cx="{j[0]:.1f}" cy="{j[1]:.1f}" r="15" fill="url(#flow)"/>')
# current pulses: bright beads staggered across lanes
for li, lane in enumerate(lanes):
    for k, t in enumerate((0.2, 0.47, 0.8)):
        i = int((t + (0.06, -0.05, 0.1)[li]) * (len(lane) - 1))
        x, y = lane[i]
        svg.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="11" fill="#FFFFFF"/>')
svg.append('</g></svg>')
open('design/appIcon.svg', 'w').write("\n".join(svg))
print("wrote design/appIcon.svg")
