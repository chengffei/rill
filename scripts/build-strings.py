#!/usr/bin/env python3
"""Generates Sources/RillApp/Translations.swift from Localization/Translations.json.

Simplified Chinese and English live inline in L("中文", "English", args...).
The other languages are keyed by the English text. This script also checks
that every L() string in the sources has all translations and that each
translation keeps the English placeholders. Run it after adding or changing
a string: scripts/build-strings.py (exit code 1 on any problem).
"""
import json, re, sys, pathlib
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources/RillApp"
JSON = ROOT / "Localization/Translations.json"
OUT = SOURCES / "Translations.swift"
LANGS = ["zh-Hant", "ja", "ko", "de", "fr", "es"]
PLACEHOLDER = re.compile(r"%(?:\d+\$)?[@d]|%\.\d+f|%%")


def literal(s, i):
    """Parses the Swift string literal at s[i]; returns (end, text, has_interpolation)."""
    i += 1
    out, interp = "", False
    while True:
        c = s[i]
        if c == "\\":
            if s[i + 1] == "(":
                interp, depth, i = True, 1, i + 2
                while depth:
                    if s[i] == '"':
                        i, _, _ = literal(s, i)
                        continue
                    depth += {"(": 1, ")": -1}.get(s[i], 0)
                    i += 1
                continue
            out += {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}.get(s[i + 1], s[i:i + 2])
            i += 2
            continue
        if c == '"':
            return i + 1, out, interp
        out += c
        i += 1


def skip(s, i):
    while s[i] in " \t\n":
        i += 1
    return i


def source_strings():
    found, problems = {}, []
    for path in sorted(SOURCES.glob("*.swift")):
        if path == OUT:
            continue
        s = path.read_text()
        code = re.sub(r"//[^\n]*", lambda m: " " * len(m.group()), s)  # ignore comments
        for m in re.finditer(r"(?<![A-Za-z0-9_.])L\(", code):
            j = skip(s, m.end())
            if s[j] != '"':
                continue  # the definition, not a call
            where = f"{path.name}:{s.count(chr(10), 0, m.start()) + 1}"
            j, zh, i1 = literal(s, j)
            j = skip(s, skip(s, j) + 1)
            _, en, i2 = literal(s, j)
            if i1 or i2:
                problems.append(f"{where}: interpolation inside L(); use %@ and pass the value as an argument")
            found.setdefault(en, where)
    return found, problems


def swift(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    table = json.loads(JSON.read_text())
    used, problems = source_strings()
    for en, where in used.items():
        row = table.get(en)
        if row is None:
            problems.append(f"{where}: no translations for {en!r}")
            continue
        want = Counter(PLACEHOLDER.findall(en))
        for lang in LANGS:
            text = row.get(lang)
            if text is None:
                problems.append(f"{where}: missing {lang} for {en!r}")
            elif Counter(p.split("$")[-1] if "$" in p else p for p in PLACEHOLDER.findall(text)) != \
                    Counter(p.split("$")[-1] if "$" in p else p for p in want.elements()):
                problems.append(f"{where}: {lang} placeholders differ for {en!r}: {text!r}")
    unused = sorted(set(table) - set(used))
    keys = sorted(k for k in table if k in used)
    lines = [
        "// Generated by scripts/build-strings.py from Localization/Translations.json. Do not edit.",
        "",
        "enum Translations {",
        f"    static let languages = [{', '.join(swift(l) for l in LANGS)}]",
        "",
        "    static func lookup(_ english: String, language: String) -> String? {",
        "        guard let i = languages.firstIndex(of: language) else { return nil }",
        "        return table[english]?[i]",
        "    }",
        "",
        "    private static let table: [String: [String]] = [",
    ]
    for k in keys:
        vals = ", ".join(swift(k if table[k].get(l) is None else table[k][l]) for l in LANGS)
        lines.append(f"        {swift(k)}: [{vals}],")
    if not keys:
        lines.append("        :")
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(keys)} strings x {len(LANGS)} languages -> {OUT.relative_to(ROOT)}")
    if unused:
        print(f"{len(unused)} unused keys in Translations.json (kept): " + "; ".join(map(repr, unused[:5])))
    for p in problems:
        print("PROBLEM:", p)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
